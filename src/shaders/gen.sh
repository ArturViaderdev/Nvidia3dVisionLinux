#!/bin/sh
# Regenerates ../depth3d_spv.h from depth3d.comp (needs glslangValidator). The header is
# committed, so building the layer does not need glslang.
set -e
cd "$(dirname "$0")"
for p in 0 1 2; do glslangValidator -V --target-env vulkan1.2 -DPASS=$p depth3d.comp -o "${TMPDIR:-/tmp}/depth3d_$p.spv" >/dev/null; done
python3 - <<'PY'
import os, struct
out = ["// generated by src/shaders/gen.sh from depth3d.comp - do not edit", "#pragma once", "#include <cstdint>"]
for p, name in ((0, "kDepthSplatSpv"), (1, "kDepthResolveSpv"), (2, "kDepthMatchSpv")):
    d = open(os.environ.get("TMPDIR", "/tmp") + f"/depth3d_{p}.spv", "rb").read()
    w = struct.unpack(f"<{len(d)//4}I", d)
    out.append(f"static const uint32_t {name}[] = {{")
    for i in range(0, len(w), 8):
        out.append("  " + ", ".join(f"0x{x:08x}u" for x in w[i:i+8]) + ",")
    out.append("};")
open("../depth3d_spv.h", "w").write("\n".join(out) + "\n")
PY
echo "OK -> src/depth3d_spv.h"
